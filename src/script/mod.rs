//! `logic { ... }`: a small, typed scripting language for use case bodies.
//!
//! A script is checked by trust itself against the project's types,
//! infras and use cases, then translated to the Rust body of the use case
//! (the same scaffolding as `code {}`). It can only reach what the project
//! declares — its infras, use cases and a fixed set of functions — so
//! there's no file system, process, network or crate access outside them,
//! no `unsafe`, no unbounded loop, and no Rust to get wrong.

mod ast;
mod check;
mod lexer;
mod parser;
mod types;

use crate::parser::{Ast, CodeSpec, LogicSpec, UseCaseService};

pub use types::{Project, Ty};

/// A line / column inside a script (1-based).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pos {
    pub line: usize,
    pub col: usize,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ScriptError {
    pub pos: Pos,
    pub message: String,
}

impl ScriptError {
    pub fn new(pos: Pos, message: String) -> Self {
        ScriptError { pos, message }
    }
}

/// The script's statements, or its first syntax error.
fn parse(source: &str) -> Result<Vec<ast::Stmt>, ScriptError> {
    let chars: Vec<char> = source.chars().collect();
    parser::parse(lexer::lex(&chars, Pos { line: 1, col: 1 })?)
}

/// `file:line:col: message` with the offending line, positioned in the
/// `.tr` file when the loader recorded where the block starts.
fn locate(use_case: &str, spec: &LogicSpec, error: &ScriptError) -> String {
    let line = spec.line.max(1) + error.pos.line - 1;
    let col = if error.pos.line == 1 {
        spec.column.max(1) + error.pos.col - 1
    } else {
        error.pos.col
    };
    let text = spec.source.lines().nth(error.pos.line - 1).unwrap_or("");
    let file = if spec.file.is_empty() {
        "<logic>"
    } else {
        spec.file.as_str()
    };
    let gutter = " ".repeat(line.to_string().len());
    format!(
        "{}:{}:{}: UseCase '{}' logic: {}\n{} |\n{} | {}\n{} | {}^",
        file,
        line,
        col,
        use_case,
        error.message,
        gutter,
        line,
        text,
        gutter,
        " ".repeat(error.pos.col.saturating_sub(1))
    )
}

/// Checks `use_case`'s script and turns it into the `code {}` it stands
/// for (the generated body, plus the infras, use cases, errors and crates
/// it uses).
pub fn lower_use_case(
    project: &Project,
    use_case: &UseCaseService,
    spec: &LogicSpec,
) -> Result<CodeSpec, String> {
    let located = |e: ScriptError| locate(&use_case.name, spec, &e);
    let body = parse(&spec.source).map_err(located)?;
    let resolve = |t: &Option<crate::parser::AllowedType>, what: &str| -> Result<Ty, String> {
        match t {
            Some(t) => project
                .ty(t)
                .map_err(|e| format!("UseCase '{}': {}", use_case.name, e)),
            None => Err(format!(
                "UseCase '{}': 'logic' requires an explicit '{}'",
                use_case.name, what
            )),
        }
    };
    let target = check::Target {
        name: &use_case.name,
        input: resolve(&use_case.input, "input")?,
        output: resolve(&use_case.output, "output")?,
        unscoped: spec.unscoped,
        journal: use_case.journal.is_some(),
    };
    let lowered = check::lower(project, &target, &body).map_err(located)?;
    let origin = if spec.file.is_empty() {
        String::from("a .tr file")
    } else {
        format!("{}:{}", spec.file, spec.line)
    };
    Ok(CodeSpec {
        file: format!("the logic {{}} block at {} (generated by trust)", origin),
        infras: lowered.infras,
        errors: lowered.errors,
        deps: lowered.deps,
        use_cases: lowered.use_cases,
        inline: Some(format!(
            "// Generated by trust from the logic {{}} block at {}.\n{}",
            origin, lowered.rust
        )),
        ..Default::default()
    })
}

/// Replaces every `logic {}` with the `code {}` it stands for.
pub fn lower_all(asts: Vec<Ast>) -> Result<Vec<Ast>, String> {
    if !asts
        .iter()
        .any(|a| matches!(a, Ast::UseCase(u) if u.logic.is_some()))
    {
        return Ok(asts);
    }
    let project = Project::new(&asts);
    asts.into_iter()
        .map(|ast| match ast {
            Ast::UseCase(mut use_case) => {
                if let Some(spec) = use_case.logic.take() {
                    use_case.code = Some(lower_use_case(&project, &use_case, &spec)?);
                    if use_case.owner.as_deref() == Some("none") {
                        use_case.owner = None;
                    }
                }
                Ok(Ast::UseCase(use_case))
            }
            other => Ok(other),
        })
        .collect()
}

