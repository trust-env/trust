//! Rewrites shorthand declarations into the ones the generator knows,
//! before anything else looks at the project:
//!
//! - `resource` blocks become CRUD use cases, plus routes in every HTTP
//!   adapter listing them under `resources {}`;
//! - a psql infra's `owner:` becomes the `owner:` of every `call:` use case
//!   whose primary call targets it (`owner: none` opts out).

use std::collections::HashMap;

use crate::parser::{
    AdapterType, AllowedType, Ast, CodeSpec, HttpMethod, HttpRoute, InfraServiceType, JournalDeclaration,
    ResourceDeclaration, StatusMapping, StorageType, StructDeclaration, StructField, TypeDeclaration,
    UseCaseCall, UseCaseService,
};

/// `journal { undo: "..." }`: the toggle (undo / redo) use case, its input
/// type and its route.
fn toggle(journal: &JournalDeclaration, entity: &str) -> (Ast, Ast, HttpRoute) {
    use heck::ToSnakeCase;
    let name = format!("Toggle{}UseCase", journal.name);
    let error = format!("{}Error", name);
    let input = format!("{}ToggleRequest", journal.name);
    let body = format!(
        r#"let tx = self.{infra}.begin().await.map_err(|e| {error}::StorageError(e.to_string()))?;
match crate::trust_toggle_{journal}(&tx, user, input.id).await {{
    Ok(entry) => {{
        crate::commit_transaction(&tx).await.map_err(|e| {error}::StorageError(e.to_string()))?;
        Ok(entry)
    }}
    Err(failure) => {{
        let _ = crate::rollback_transaction(&tx).await;
        Err(match failure {{
            crate::TrustToggleError::NotFound => {error}::NotFound,
            crate::TrustToggleError::Conflict(message) => {error}::Conflict(message),
            crate::TrustToggleError::Database(message) => {error}::StorageError(message),
        }})
    }}
}}
"#,
        infra = journal.infra.to_snake_case(),
        error = error,
        journal = journal.name.to_snake_case(),
    );
    let mut uc = use_case(name.clone(), &journal.infra, "find_one", None);
    uc.calls.clear();
    uc.input = Some(AllowedType::DefinedType(input.clone()));
    uc.output = Some(AllowedType::DefinedType(entity.to_string()));
    uc.code = Some(CodeSpec {
        file: format!("(generated by trust for journal {})", journal.name),
        infras: vec![journal.infra.clone()],
        errors: vec!["Conflict".to_string()],
        inline: Some(body),
        ..Default::default()
    });
    let input_type = Ast::TypeDecl(TypeDeclaration::Struct(StructDeclaration {
        name: input,
        fields: vec![StructField { name: "id".to_string(), field_type: AllowedType::Int }],
        export: None,
    }));
    let route = HttpRoute {
        method: HttpMethod::Post,
        path: journal.undo_path.clone().unwrap_or_default(),
        input: None,
        output: None,
        use_case: name,
        status: vec![StatusMapping { target: "Conflict".to_string(), status: 409 }],
        auth: None,
        auth_explicit: false,
    };
    (Ast::UseCase(uc), input_type, route)
}

fn use_case(name: String, infra: &str, method: &str, owner: Option<String>) -> UseCaseService {
    UseCaseService {
        name,
        input: None,
        output: None,
        calls: vec![UseCaseCall { target: infra.to_string(), method: method.to_string(), errors: Vec::new() }],
        ai: None,
        blob: None,
        filters: Vec::new(),
        owner,
        code: None,
        order_by: Vec::new(),
        transaction: false,
        notify: None,
        journal: None,
        journal_text: None,
    }
}

/// The use cases and routes (with no auth yet) of one resource.
fn expand(resource: &ResourceDeclaration, entity: &str, entity_type: &str) -> (Vec<UseCaseService>, Vec<Ast>, Vec<HttpRoute>) {
    use heck::ToSnakeCase;
    let base = resource.path.trim_end_matches('/');
    let item = format!("{}/:id", base);
    let mut use_cases = Vec::new();
    let mut types = Vec::new();
    let mut routes = Vec::new();
    let route = |method: HttpMethod, path: String, use_case: String| HttpRoute {
        method,
        path: if path.is_empty() { "/".to_string() } else { path },
        input: None,
        output: None,
        use_case,
        status: Vec::new(),
        auth: None,
        auth_explicit: false,
    };
    for op in &resource.operations {
        // A singleton's `get`: the owner's row, or one built from the defaults.
        if resource.singleton && op.kind == "get" {
            let name = format!("Get{}UseCase", entity);
            let input = format!("{}Request", resource.name);
            let owner = resource.owner.clone().unwrap_or_default();
            let mut uc = use_case(name.clone(), &resource.infra, "find_one", None);
            uc.calls.clear();
            uc.input = Some(AllowedType::DefinedType(input.clone()));
            uc.output = Some(AllowedType::DefinedType(entity_type.to_string()));
            uc.code = Some(CodeSpec {
                file: format!("(generated by trust for resource {})", resource.name),
                infras: vec![resource.infra.clone()],
                inline: Some(format!(
                    "Ok(self.{}.get_or_default({:?}, user).await?)\n",
                    resource.infra.to_snake_case(),
                    owner
                )),
                ..Default::default()
            });
            use_cases.push(uc);
            types.push(Ast::TypeDecl(TypeDeclaration::Struct(StructDeclaration {
                name: input,
                fields: Vec::new(),
                export: None,
            })));
            routes.push(route(HttpMethod::Get, base.to_string(), name));
            continue;
        }
        let (name, method, http, path) = match op.kind.as_str() {
            "save" => (format!("Save{}UseCase", entity), "save_or_patch", HttpMethod::Put, base.to_string()),
            "list" => (format!("List{}UseCase", resource.name), "list", HttpMethod::Get, base.to_string()),
            "get" => (format!("Get{}UseCase", entity), "find_one", HttpMethod::Get, item.clone()),
            "create" => (format!("Create{}UseCase", entity), "save_one", HttpMethod::Post, base.to_string()),
            "upsert" => (format!("Upsert{}UseCase", entity), "upsert_one", HttpMethod::Put, base.to_string()),
            "update" => (format!("Update{}UseCase", entity), "update_one", HttpMethod::Put, item.clone()),
            "patch" => (format!("Patch{}UseCase", entity), "patch_one", HttpMethod::Patch, item.clone()),
            _ => (format!("Delete{}UseCase", entity), "delete", HttpMethod::Delete, item.clone()),
        };
        let mut uc = use_case(name.clone(), &resource.infra, method, resource.owner.clone());
        uc.filters = op.filters.clone();
        uc.order_by = op.order_by.clone();
        use_cases.push(uc);
        routes.push(route(http, path, name));
    }
    (use_cases, types, routes)
}

/// What a mirror needs to know about the project.
struct MirrorEnv<'a> {
    infra_entities: &'a HashMap<String, String>,
    infra_owners: &'a HashMap<String, String>,
    ics_infras: Vec<String>,
    use_cases: Vec<String>,
    struct_fields: HashMap<String, Vec<String>>,
    app_tz: Option<String>,
}

/// `mirror Name {...}`: a `code` use case `{Name}UseCase` (input
/// `{Name}Request { days }`, output `MirrorReport`).
fn mirror_use_case(mirror: &crate::parser::MirrorDeclaration, env: &MirrorEnv) -> Result<(UseCaseService, Ast), String> {
    use crate::parser::{MapValue, MirrorScope};
    use heck::ToSnakeCase;
    let err = |what: String| format!("mirror '{}': {}", mirror.name, what);
    let entity = env
        .infra_entities
        .get(&mirror.into)
        .ok_or_else(|| err(format!("'{}' is not a psql infra", mirror.into)))?;
    let fields = env.struct_fields.get(entity).cloned().unwrap_or_default();
    let owner = env.infra_owners.get(&mirror.into).cloned();
    for (field, _) in mirror.map.iter() {
        if !fields.contains(field) {
            return Err(err(format!("'{}' has no field '{}'", entity, field)));
        }
        if Some(field) == owner.as_ref() {
            return Err(err(format!("'{}' is the owner: it is the user running the mirror", field)));
        }
    }
    for field in mirror.key.iter().chain(mirror.scope.iter().map(|(f, _)| f)) {
        if !fields.contains(field) {
            return Err(err(format!("'{}' has no field '{}'", entity, field)));
        }
    }
    let key_fields: Vec<&String> = mirror.key.iter().filter(|k| Some(*k) != owner.as_ref()).collect();
    for key in &key_fields {
        if !mirror.map.iter().any(|(f, _)| f == *key) {
            return Err(err(format!("key field '{}' must be set by map {{}}", key)));
        }
    }

    let into = mirror.into.to_snake_case();
    let source_is_infra = env.ics_infras.contains(&mirror.source);
    let source_is_use_case = env.use_cases.contains(&mirror.source);
    if !source_is_infra && !source_is_use_case {
        return Err(err(format!(
            "source '{}' must be an ics_feed infra or a use case whose output has 'items'",
            mirror.source
        )));
    }
    let source = mirror.source.to_snake_case();
    let (configured, items) = if source_is_infra {
        (
            format!("self.{}.is_configured()", source),
            format!("self.{}.occurrences(from, to).await?", source),
        )
    } else {
        (
            "true".to_string(),
            format!(
                "{{
            let source_input = serde_json::from_value(serde_json::json!({{ \"from\": from, \"to\": to }}))
                .map_err(|e| format!(\"{source_name} input: {{}}\", e))?;
            let source_output = self.{source}.execute(user, source_input).await.map_err(|e| format!(\"{source_name}: {{:?}}\", e))?;
            // `configured: false` in the source's output: nothing is written or removed.
            if serde_json::to_value(&source_output).ok().and_then(|v| v.get(\"configured\").and_then(|c| c.as_bool())) == Some(false) {{
                return Ok(None);
            }}
            source_output.items
        }}",
                source = source,
                source_name = mirror.source
            ),
        )
    };

    let zone = mirror.window_zone.clone().or_else(|| env.app_tz.clone());
    if let Some(zone) = &zone {
        zone.parse::<chrono_tz::Tz>().map_err(|_| err(format!("unknown time zone '{}'", zone)))?;
    }
    let zone_expr = match &zone {
        Some(zone) => format!("{:?}.parse::<chrono_tz::Tz>().expect(\"time zone checked by trust\")", zone),
        None => "chrono_tz::UTC".to_string(),
    };
    let from_expr = match mirror.window_from.as_str() {
        "now" => "chrono::Utc::now()".to_string(),
        which => format!(
            "{{
        use chrono::TimeZone;
        let zone = {zone};
        let today = chrono::Utc::now().with_timezone(&zone).date_naive();
        let day = {day};
        zone.from_local_datetime(&day.and_time(chrono::NaiveTime::MIN))
            .earliest()
            .map(|t| t.with_timezone(&chrono::Utc))
            .unwrap_or_else(chrono::Utc::now)
    }}",
            zone = zone_expr,
            day = if which == "week_start" {
                "today - chrono::Duration::days(chrono::Datelike::weekday(&today).num_days_from_monday() as i64)"
            } else {
                "today"
            }
        ),
    };

    let mut scope = String::new();
    for (field, rule) in &mirror.scope {
        scope.push_str(&match rule {
            MirrorScope::Equals(serde_json::Value::String(text)) => format!(".eq({:?}, {:?})", field, text),
            MirrorScope::Equals(other) => format!(".eq({:?}, {:?})", field, other.to_string()),
            MirrorScope::After(from) => format!(".gt({:?}, {}.to_rfc3339())", field, if *from { "from" } else { "to" }),
            MirrorScope::Before(from) => format!(".lt({:?}, {}.to_rfc3339())", field, if *from { "from" } else { "to" }),
        });
    }
    let mut inits = String::new();
    for (field, value) in &mirror.map {
        let expr = match value {
            MapValue::Path(path) => format!("TrustMirrorInto::trust_into(item.{}.clone())", path.join(".")),
            MapValue::Literal(v) => format!(
                "serde_json::from_str({:?}).map_err(|e| format!(\"map: '{}': {{}}\", e))?",
                v.to_string(),
                field
            ),
        };
        inits.push_str(&format!("                {}: {},\n", field, expr));
    }
    if let Some(owner) = &owner {
        inits.push_str(&format!("                {}: user,\n", owner));
    }
    let key_of = |var: &str| {
        format!(
            "format!(\"{{:?}}\", ({}))",
            key_fields.iter().map(|k| format!("&{}.{},", var, k)).collect::<String>()
        )
    };
    // `skip {}`: helpers and regexes before the loop, one test per line in it.
    let mut skip_setup = String::new();
    let mut skip_tests = Vec::new();
    for (i, rule) in mirror.skip.iter().enumerate() {
        use crate::parser::FilterOperator as Op;
        let text_of = |v: &serde_json::Value| match v {
            serde_json::Value::String(s) => s.clone(),
            other => other.to_string(),
        };
        let field = format!("trust_mirror_text(serde_json::to_value(&item.{}).unwrap_or_default())", rule.path.join("."));
        let shown = format!("item.{}", rule.path.join("."));
        let mut regex_test = |pattern: String| -> Result<String, String> {
            regex::Regex::new(&pattern).map_err(|e| err(format!("skip: {}: invalid pattern: {}", shown, e)))?;
            skip_setup.push_str(&format!("let trust_skip_{} = regex::Regex::new({:?}).expect(\"pattern checked by trust\");\n", i, pattern));
            Ok(format!("trust_skip_{}.is_match(&{})", i, field))
        };
        let like = |pattern: &str| {
            let mut re = String::from("^");
            for c in pattern.chars() {
                match c {
                    '%' => re.push_str(".*"),
                    '_' => re.push('.'),
                    other => re.push_str(&regex::escape(&other.to_string())),
                }
            }
            re.push('$');
            re
        };
        let literal = text_of(&rule.value);
        let test = match &rule.operator {
            None => regex_test(literal)?,
            Some(Op::Like) => regex_test(like(&literal))?,
            Some(Op::ILike) => regex_test(format!("(?i){}", like(&literal)))?,
            Some(Op::Contains) => format!("{}.to_lowercase().contains(&{:?}.to_lowercase())", field, literal),
            Some(Op::Eq) => format!("{} == {:?}", field, literal),
            Some(Op::NotEq) => format!("{} != {:?}", field, literal),
            Some(op @ (Op::Gt | Op::Gte | Op::Lt | Op::Lte)) => {
                let wanted = match op {
                    Op::Gt => "== std::cmp::Ordering::Greater",
                    Op::Gte => "!= std::cmp::Ordering::Less",
                    Op::Lt => "== std::cmp::Ordering::Less",
                    _ => "!= std::cmp::Ordering::Greater",
                };
                format!("trust_mirror_cmp(&{}, {:?}) {}", field, literal, wanted)
            }
            Some(op @ (Op::In | Op::NotIn)) => {
                let serde_json::Value::Array(values) = &rule.value else {
                    return Err(err(format!("skip: {} in: expected a [list]", shown)));
                };
                let list: Vec<String> = values.iter().map(|v| format!("{:?}", text_of(v))).collect();
                format!("{}[{}].contains(&{}.as_str())", if matches!(op, Op::NotIn) { "!" } else { "" }, list.join(", "), field)
            }
        };
        skip_tests.push(test);
    }
    let (skip_helpers, skip_check) = if skip_tests.is_empty() {
        (String::new(), String::new())
    } else {
        (
            format!(
                r#"// `skip {{}}`: a source value as text, and comparisons (numbers when both are).
fn trust_mirror_text(value: serde_json::Value) -> String {{
    match value {{
        serde_json::Value::String(text) => text,
        serde_json::Value::Null => String::new(),
        other => other.to_string(),
    }}
}}
#[allow(dead_code)]
fn trust_mirror_cmp(a: &str, b: &str) -> std::cmp::Ordering {{
    match (a.parse::<f64>(), b.parse::<f64>()) {{
        (Ok(x), Ok(y)) => x.partial_cmp(&y).unwrap_or(std::cmp::Ordering::Equal),
        _ => a.cmp(b),
    }}
}}
{}"#,
                skip_setup
            ),
            format!("        if {} {{\n            continue;\n        }}\n", skip_tests.iter().map(|t| format!("({})", t)).collect::<Vec<_>>().join("\n            || ")),
        )
    };
    let (owner_filter, owner_arg) = match &owner {
        Some(owner) => (format!(".eq({:?}, user)", owner), format!("Some({:?})", owner)),
        None => (String::new(), "None".to_string()),
    };
    let body = format!(
        r#"// Converts a source value into a field: as is, or into an Option.
trait TrustMirrorInto<T> {{
    fn trust_into(self) -> T;
}}
impl<T> TrustMirrorInto<T> for T {{
    fn trust_into(self) -> T {{
        self
    }}
}}
impl<T> TrustMirrorInto<Option<T>> for T {{
    fn trust_into(self) -> Option<T> {{
        Some(self)
    }}
}}
let days = input.days.unwrap_or({days}).clamp(1, 366);
let from = {from_expr};
let to = from + chrono::Duration::days(days);
if !{configured} {{
    return Ok(MirrorReport {{ configured: false, written: 0, removed: 0, error: None }});
}}
{skip_helpers}let outcome: Result<Option<(i64, i64)>, String> = async {{
    let items = {items};
    let mut keep = std::collections::HashSet::new();
    let mut written = 0i64;
    for item in items.iter() {{
{skip_check}        #[allow(clippy::needless_update)]
        let row = {entity} {{
{inits}                ..Default::default()
        }};
        keep.insert({key_row});
        if self.{into}.upsert_one(row, {owner_arg}).await.map_err(|e| format!("{{:?}}", e))?.is_some() {{
            written += 1;
        }}
    }}
    let local = self
        .{into}
        .query(Query::new(){owner_filter}{scope}.limit(100_000))
        .await
        .map_err(|e| format!("{{:?}}", e))?;
    let mut removed = 0i64;
    for row in local {{
        if !keep.contains(&{key_local}) {{
            self.{into}.delete(row.id).await.map_err(|e| format!("{{:?}}", e))?;
            removed += 1;
        }}
    }}
    Ok(Some((written, removed)))
}}
.await;
if let Err(error) = &outcome {{
    tracing::warn!(mirror = "{name}", %error, "mirror failed");
}}
Ok(match outcome {{
    Ok(Some((written, removed))) => MirrorReport {{ configured: true, written, removed, error: None }},
    Ok(None) => MirrorReport {{ configured: false, written: 0, removed: 0, error: None }},
    Err(error) => MirrorReport {{ configured: true, written: 0, removed: 0, error: Some(error) }},
}})
"#,
        days = mirror.window_days,
        skip_helpers = skip_helpers,
        skip_check = skip_check,
        from_expr = from_expr,
        configured = configured,
        items = items,
        entity = entity,
        inits = inits,
        key_row = key_of("row"),
        key_local = key_of("row"),
        into = into,
        owner_arg = owner_arg,
        owner_filter = owner_filter,
        scope = scope,
        name = mirror.name,
    );
    let name = format!("{}UseCase", mirror.name);
    let input = format!("{}Request", mirror.name);
    let mut uc = use_case(name, &mirror.into, "list", None);
    uc.calls.clear();
    uc.input = Some(AllowedType::DefinedType(input.clone()));
    uc.output = Some(AllowedType::DefinedType("MirrorReport".to_string()));
    let mut infras = vec![mirror.into.clone()];
    let mut use_cases = Vec::new();
    if source_is_infra {
        infras.push(mirror.source.clone());
    } else {
        use_cases.push(mirror.source.clone());
    }
    uc.code = Some(CodeSpec {
        file: format!("(generated by trust for mirror {})", mirror.name),
        infras,
        use_cases,
        deps: {
            let mut deps = vec![("chrono-tz".to_string(), "0.10".to_string()), ("tracing".to_string(), "0.1".to_string())];
            if mirror.skip.iter().any(|r| {
                matches!(r.operator, None | Some(crate::parser::FilterOperator::Like) | Some(crate::parser::FilterOperator::ILike))
            }) {
                deps.push(("regex".to_string(), "1".to_string()));
            }
            deps
        },
        inline: Some(body),
        ..Default::default()
    });
    let input_type = Ast::TypeDecl(TypeDeclaration::Struct(StructDeclaration {
        name: input,
        fields: vec![StructField { name: "days".to_string(), field_type: AllowedType::Option(Box::new(AllowedType::Int)) }],
        export: None,
    }));
    Ok((uc, input_type))
}

/// A notify-mode `http_client` infra sending on `channels`.
fn notify_infra(
    name: String,
    channels: Vec<crate::parser::ChannelDeclaration>,
    default: Vec<String>,
    fallback: Option<String>,
    routing: Vec<(String, Vec<String>)>,
    record: Option<String>,
    record_owner: Option<String>,
) -> Ast {
    Ast::Infra(crate::parser::InfraService {
        name,
        service_type: InfraServiceType::HttpClient(crate::parser::HttpClientInfraService {
            base_url: String::new(),
            headers: Vec::new(),
            retry: 2,
            timeout_secs: 15,
            oauth2: None,
            ics: None,
            notify: Some(crate::parser::NotifyOptions { channels, default, fallback, routing, record, record_owner }),
        }),
    })
}

/// `{result.a.b}` templates as Rust statements appending to `reply`.
fn reply_code(template: &str, camel: bool) -> String {
    let re = regex::Regex::new(r"\{result((?:\.[A-Za-z0-9_]+)*)\}").expect("valid regex");
    let mut code = String::new();
    let mut last = 0;
    for caps in re.captures_iter(template) {
        let whole = caps.get(0).expect("match");
        if whole.start() > last {
            code.push_str(&format!("        reply.push_str({:?});\n", &template[last..whole.start()]));
        }
        let mut access = "result".to_string();
        for part in caps[1].split('.').filter(|p| !p.is_empty()) {
            access.push_str(&format!("[{:?}]", crate::generator::schema::wire_name(part, camel)));
        }
        code.push_str(&format!(
            "        reply.push_str(&match &{} {{ serde_json::Value::String(text) => text.clone(), serde_json::Value::Null => String::new(), other => other.to_string() }});\n",
            access
        ));
        last = whole.end();
    }
    if last < template.len() {
        code.push_str(&format!("        reply.push_str({:?});\n", &template[last..]));
    }
    code
}

/// `bot Name {...}`: its channel infra, its webhook use case and route.
fn bot_parts(
    bot: &crate::parser::BotDeclaration,
    channels: &HashMap<String, crate::parser::ChannelDeclaration>,
    notifications: &[crate::parser::NotificationsDeclaration],
    infra_owners: &HashMap<String, String>,
    use_cases: &[String],
    camel: bool,
) -> Result<(Vec<Ast>, HttpRoute), String> {
    use heck::ToSnakeCase;
    let err = |what: String| format!("bot '{}': {}", bot.name, what);
    let channel = channels.get(&bot.channel).ok_or_else(|| err(format!("unknown channel '{}'", bot.channel)))?;
    if channel.kind != "telegram" {
        return Err(err(format!("channel '{}' must be a telegram channel", bot.channel)));
    }
    for uc in bot.commands.iter().chain(bot.on_reply.iter()).map(|(_, u)| u).chain(bot.default.iter()) {
        if !use_cases.contains(uc) {
            return Err(err(format!("unknown use_case '{}'", uc)));
        }
    }
    let channel_infra = format!("{}Channel", bot.name);
    let client = channel_infra.to_snake_case();
    let error = format!("{}UseCaseError", bot.name);
    let record = if bot.on_reply.is_empty() {
        None
    } else {
        let notify = notifications
            .iter()
            .find(|n| {
                n.infra.is_some()
                    && (n.default.contains(&bot.channel)
                        || n.fallback.as_ref() == Some(&bot.channel)
                        || n.routing.iter().any(|(_, c)| c.contains(&bot.channel)))
            })
            .ok_or_else(|| err(format!("on_reply needs a notifications {{ infra: ... }} sending on '{}'", bot.channel)))?;
        notify.infra.clone()
    };
    let mut code = String::new();
    code.push_str(&format!(
        r#"let _ = user;
let user: i64 = {user};
// Telegram resends an update until it gets a 2xx: failures are reported, not raised.
let secret: String = {secret};
if !secret.is_empty() && input.headers.get("x-telegram-bot-api-secret-token") != Some(&secret) {{
    return Err({error}::Forbidden("wrong webhook secret".to_string()));
}}
let update: serde_json::Value = serde_json::from_str(&input.body).unwrap_or_default();
let message = &update["message"];
let text = message["text"].as_str().unwrap_or_default().trim().to_string();
let chat = message["chat"]["id"].as_i64().map(|id| id.to_string());
if text.is_empty() || chat.is_none() || chat != self.{client}.chat_of({channel:?}) {{
    return Ok(BotAck {{ handled: false, reply: None, error: None }});
}}
let message_id = message["message_id"].as_i64().map(|id| id.to_string());
let reply_to = message["reply_to_message"]["message_id"].as_i64();
let (command, rest) = match text.strip_prefix('/') {{
    Some(after) => {{
        let (head, rest) = after.split_once(char::is_whitespace).unwrap_or((after, ""));
        (Some(head.split('@').next().unwrap_or_default().to_lowercase()), rest.trim().to_string())
    }}
    None => (None, text.clone()),
}};
let mut replied_kind: Option<&str> = None;
"#,
        user = bot.user,
        secret = bot
            .secret
            .as_deref()
            .map(crate::generator::rust_code::env_template::to_rust_expr_lenient)
            .unwrap_or_else(|| "String::new()".to_string()),
        error = error,
        client = client,
        channel = bot.channel,
    ));
    if let Some(record) = &record {
        let owner = infra_owners.get(record).cloned();
        let kinds: Vec<String> = bot.on_reply.iter().map(|(k, _)| format!("{:?}", k)).collect();
        code.push_str(&format!(
            r#"if let (None, Some(id)) = (&command, reply_to) {{
    for kind in [{kinds}] {{
        let found = self
            .{record}
            .query(Query::new(){owner}.eq("kind", kind).eq("external_id", id).limit(1))
            .await
            .map_err(|e| {error}::StorageError(format!("{{:?}}", e)))?;
        if !found.is_empty() {{
            replied_kind = Some(kind);
            break;
        }}
    }}
}}
"#,
            kinds = kinds.join(", "),
            record = record.to_snake_case(),
            owner = owner.map(|o| format!(".eq({:?}, user)", o)).unwrap_or_default(),
            error = error,
        ));
    }
    let reply = bot.reply.as_deref().map(|t| reply_code(t, camel));
    let run = |uc: &str, input: &str| {
        format!(
            r#"{{
        let use_case_input = serde_json::from_value(serde_json::json!({{ "text": {input} }}))
            .map_err(|e| format!("{uc} input: {{}}", e));
        match use_case_input {{
            Ok(use_case_input) => self
                .{field}
                .execute(user, use_case_input)
                .await
                .map(|output| serde_json::to_value(&output).unwrap_or_default())
                .map_err(|e| format!("{uc}: {{:?}}", e)),
            Err(e) => Err(e),
        }}
    }}"#,
            uc = uc,
            field = uc.to_snake_case(),
            input = input
        )
    };
    code.push_str("let outcome: Option<Result<serde_json::Value, String>> = match (replied_kind, command.as_deref()) {
");
    for (kind, uc) in &bot.on_reply {
        code.push_str(&format!("    (Some({:?}), _) => Some({}),
", kind, run(uc, "text")));
    }
    for (name, uc) in &bot.commands {
        code.push_str(&format!("    (_, Some({:?})) => Some({}),
", name.to_lowercase(), run(uc, "rest")));
    }
    code.push_str("    (_, Some(_)) => None,
");
    match &bot.default {
        Some(uc) => code.push_str(&format!("    (_, None) => Some({}),
", run(uc, "text"))),
        None => code.push_str("    (_, None) => None,
"),
    }
    code.push_str("};
");
    code.push_str(&format!(
        r#"let Some(outcome) = outcome else {{
    return Ok(BotAck {{ handled: false, reply: None, error: None }});
}};
let (reply, error) = match outcome {{
    Ok(result) => {{
        let _ = &result;
        let mut reply = String::new();
{reply}        (Some(reply).filter(|r| !r.trim().is_empty()), None)
    }}
    Err(error) => {{
        tracing::warn!(bot = {name:?}, %error, "bot command failed");
        (None, Some(error))
    }}
}};
if let Some(reply) = &reply {{
    if let Err(error) = self.{client}.send_to({channel:?}, "reply", reply, message_id.as_deref()).await {{
        tracing::warn!(bot = {name:?}, %error, "bot reply not sent");
    }}
}}
Ok(BotAck {{ handled: true, reply, error }})
"#,
        reply = reply.unwrap_or_default(),
        name = bot.name,
        client = client,
        channel = bot.channel,
    ));

    let name = format!("{}UseCase", bot.name);
    let mut uc = use_case(name.clone(), &channel_infra, "list", None);
    uc.calls.clear();
    uc.input = Some(AllowedType::DefinedType("RawRequest".to_string()));
    uc.output = Some(AllowedType::DefinedType("BotAck".to_string()));
    let mut infras = vec![channel_infra.clone()];
    infras.extend(record.clone());
    let mut called: Vec<String> = Vec::new();
    for uc in bot.commands.iter().chain(bot.on_reply.iter()).map(|(_, u)| u).chain(bot.default.iter()) {
        if !called.contains(uc) {
            called.push(uc.clone());
        }
    }
    uc.code = Some(CodeSpec {
        file: format!("(generated by trust for bot {})", bot.name),
        infras,
        use_cases: called,
        errors: vec!["Forbidden".to_string()],
        deps: vec![("tracing".to_string(), "0.1".to_string())],
        inline: Some(code),
        ..Default::default()
    });
    let infra = notify_infra(channel_infra, vec![channel.clone()], vec![bot.channel.clone()], None, Vec::new(), None, None);
    let route = HttpRoute {
        method: HttpMethod::Post,
        path: bot.path.clone(),
        input: None,
        output: None,
        use_case: name,
        status: vec![StatusMapping { target: "Forbidden".to_string(), status: 403 }],
        auth: None,
        auth_explicit: true,
    };
    Ok((vec![infra, Ast::UseCase(uc)], route))
}

pub fn desugar(asts: Vec<Ast>) -> Result<Vec<Ast>, String> {
    let mut infra_entities: HashMap<String, String> = HashMap::new();
    let mut infra_owners: HashMap<String, String> = HashMap::new();
    for ast in &asts {
        if let Ast::Infra(infra) = ast {
            if let InfraServiceType::Storage(StorageType::Psql(psql)) = &infra.service_type {
                if let AllowedType::DefinedType(entity) = &psql.entity {
                    infra_entities.insert(infra.name.clone(), entity.clone());
                }
                if let Some(owner) = &psql.owner {
                    infra_owners.insert(infra.name.clone(), owner.clone());
                }
            }
        }
    }

    let infra_sets: HashMap<String, Vec<String>> = asts
        .iter()
        .filter_map(|ast| match ast {
            Ast::InfraSet(name, members) => Some((name.clone(), members.clone())),
            _ => None,
        })
        .collect();

    let mirror_env = MirrorEnv {
        infra_entities: &infra_entities,
        infra_owners: &infra_owners,
        ics_infras: asts
            .iter()
            .filter_map(|ast| match ast {
                Ast::Infra(i) if matches!(&i.service_type, InfraServiceType::HttpClient(c) if c.ics.is_some()) => Some(i.name.clone()),
                _ => None,
            })
            .collect(),
        use_cases: asts
            .iter()
            .filter_map(|ast| match ast {
                Ast::UseCase(u) => Some(u.name.clone()),
                _ => None,
            })
            .collect(),
        struct_fields: asts
            .iter()
            .filter_map(|ast| match ast {
                Ast::TypeDecl(TypeDeclaration::Struct(s)) => Some((s.name.clone(), s.fields.iter().map(|f| f.name.clone()).collect())),
                _ => None,
            })
            .collect(),
        app_tz: asts.iter().rev().find_map(|ast| match ast {
            Ast::Config(c) => c.tz.clone(),
            _ => None,
        }),
    };
    let channels: HashMap<String, crate::parser::ChannelDeclaration> = asts
        .iter()
        .filter_map(|ast| match ast {
            Ast::Channel(c) => Some((c.name.clone(), c.clone())),
            _ => None,
        })
        .collect();
    let notifications: Vec<crate::parser::NotificationsDeclaration> = asts
        .iter()
        .filter_map(|ast| match ast {
            Ast::Notifications(n) => Some(n.clone()),
            _ => None,
        })
        .collect();
    let camel = asts.iter().any(|ast| matches!(ast, Ast::Config(c) if c.json_case.as_deref() == Some("camel")));
    let has_bot_ack = asts
        .iter()
        .any(|ast| matches!(ast, Ast::TypeDecl(TypeDeclaration::Struct(s)) if s.name == "BotAck"));
    let mut bot_ack_added = false;
    let has_mirror_report = asts
        .iter()
        .any(|ast| matches!(ast, Ast::TypeDecl(TypeDeclaration::Struct(s)) if s.name == "MirrorReport"));
    let mut mirror_report_added = false;
    // (infra, key) of mirrors: the key becomes the infra's upsert key.
    let mut mirror_keys: Vec<(String, Vec<String>)> = Vec::new();
    let mut resource_routes: HashMap<String, Vec<HttpRoute>> = HashMap::new();
    // (infra, owner, defaults) of singleton resources.
    let mut singletons: Vec<(String, String, Vec<(String, serde_json::Value)>)> = Vec::new();
    let mut out: Vec<Ast> = Vec::new();
    for ast in &asts {
        if let Ast::Journal(journal) = ast {
            if journal.undo_path.is_some() {
                let entity = infra_entities.get(&journal.infra).ok_or_else(|| {
                    format!("journal '{}': '{}' is not a psql infra", journal.name, journal.infra)
                })?;
                let (uc, input, route) = toggle(journal, entity);
                out.push(uc);
                out.push(input);
                resource_routes.insert(journal.name.clone(), vec![route]);
            }
        }
    }
    for ast in asts {
        match ast {
            Ast::Resource(resource) => {
                let entity = infra_entities.get(&resource.infra).ok_or_else(|| {
                    format!("resource '{}': '{}' is not a psql infra", resource.name, resource.infra)
                })?;
                let singular = resource.singular.clone().unwrap_or_else(|| entity.clone());
                let (mut use_cases, types, routes) = expand(&resource, &singular, entity);
                out.extend(types);
                if resource.singleton {
                    singletons.push((resource.infra.clone(), resource.owner.clone().unwrap_or_default(), resource.defaults.clone()));
                }
                if let Some(journal) = &resource.journal {
                    for uc in &mut use_cases {
                        let writes = uc.calls.iter().any(|c| c.method != "list" && c.method != "find_one");
                        if writes {
                            uc.journal = Some(journal.clone());
                        }
                    }
                }
                out.extend(use_cases.into_iter().map(Ast::UseCase));
                resource_routes.insert(resource.name.clone(), routes);
            }
            Ast::InfraSet(..) => {}
            Ast::Channel(_) => {}
            Ast::Notifications(n) => {
                let mut used: Vec<crate::parser::ChannelDeclaration> = Vec::new();
                let named = n.default.iter().chain(n.fallback.iter()).chain(n.routing.iter().flat_map(|(_, c)| c.iter()));
                for channel in named {
                    if channel == "log" || used.iter().any(|c| &c.name == channel) {
                        continue;
                    }
                    let decl = channels
                        .get(channel)
                        .ok_or_else(|| format!("notifications '{}': unknown channel '{}' (declare it with `channel {} {{ ... }}`, or use log)", n.name, channel, channel))?;
                    used.push(decl.clone());
                }
                if let Some(infra) = &n.infra
                    && !infra_entities.contains_key(infra)
                {
                    return Err(format!("notifications '{}': '{}' is not a psql infra", n.name, infra));
                }
                out.push(notify_infra(n.name.clone(), used, n.default.clone(), n.fallback.clone(), n.routing.clone(), n.infra.clone(), n.infra.as_ref().and_then(|i| infra_owners.get(i).cloned())));
            }
            Ast::Bot(bot) => {
                let (parts, route) = bot_parts(&bot, &channels, &notifications, &infra_owners, &mirror_env.use_cases, camel)?;
                out.extend(parts);
                if !has_bot_ack && !bot_ack_added {
                    bot_ack_added = true;
                    let field = |name: &str, field_type: AllowedType| StructField { name: name.to_string(), field_type };
                    out.push(Ast::TypeDecl(TypeDeclaration::Struct(StructDeclaration {
                        name: "BotAck".to_string(),
                        fields: vec![
                            field("handled", AllowedType::Bool),
                            field("reply", AllowedType::Option(Box::new(AllowedType::String))),
                            field("error", AllowedType::Option(Box::new(AllowedType::String))),
                        ],
                        export: None,
                    })));
                }
                resource_routes.insert(bot.name.clone(), vec![route]);
            }
            Ast::Mirror(mirror) => {
                let (uc, input) = mirror_use_case(&mirror, &mirror_env)?;
                out.push(Ast::UseCase(uc));
                out.push(input);
                if !has_mirror_report && !mirror_report_added {
                    mirror_report_added = true;
                    let field = |name: &str, field_type: AllowedType| StructField { name: name.to_string(), field_type };
                    out.push(Ast::TypeDecl(TypeDeclaration::Struct(StructDeclaration {
                        name: "MirrorReport".to_string(),
                        fields: vec![
                            field("configured", AllowedType::Bool),
                            field("written", AllowedType::Int),
                            field("removed", AllowedType::Int),
                            field("error", AllowedType::Option(Box::new(AllowedType::String))),
                        ],
                        export: None,
                    })));
                }
                mirror_keys.push((mirror.into.clone(), mirror.key.clone()));
            }
            other => out.push(other),
        }
    }

    for ast in &mut out {
        match ast {
            // A singleton's infra: one row per owner, the resource's defaults.
            Ast::Infra(infra) => {
                if let InfraServiceType::Storage(StorageType::Psql(psql)) = &mut infra.service_type {
                    for (target, key) in &mirror_keys {
                        if target == &infra.name && psql.unique.first() != Some(key) {
                            psql.unique.retain(|existing| existing != key);
                            psql.unique.insert(0, key.clone());
                        }
                    }
                    for (target, owner, defaults) in &singletons {
                        if target != &infra.name {
                            continue;
                        }
                        if !psql.unique.iter().any(|key| key == &vec![owner.clone()]) {
                            psql.unique.insert(0, vec![owner.clone()]);
                        }
                        for (field, value) in defaults {
                            if !psql.defaults.iter().any(|(f, _)| f == field) {
                                psql.defaults.push((field.clone(), crate::parser::DefaultValue::Literal(value.clone())));
                            }
                        }
                    }
                }
            }
            Ast::Adapter(adapter) => {
                if let AdapterType::Http(http) = &mut adapter.adapter_type {
                    for name in &http.resources {
                        let routes = resource_routes.get(name).ok_or_else(|| {
                            format!("adapter '{}' lists unknown resource, bot or journal (with undo) '{}'", adapter.name, name)
                        })?;
                        for route in routes {
                            let mut route = route.clone();
                            // A bot's webhook checks its own secret.
                            if !route.auth_explicit {
                                route.auth = http.default_auth.clone();
                            }
                            http.routes.push(route);
                        }
                    }
                }
            }
            Ast::UseCase(use_case) => {
                if let Some(code) = &mut use_case.code {
                    let mut infras: Vec<String> = Vec::new();
                    for name in &code.infras {
                        for member in infra_sets.get(name).cloned().unwrap_or_else(|| vec![name.clone()]) {
                            if !infras.contains(&member) {
                                infras.push(member);
                            }
                        }
                    }
                    code.infras = infras;
                }
                if use_case.owner.as_deref() == Some("none") {
                    use_case.owner = None;
                } else if use_case.owner.is_none() && use_case.code.is_none() {
                    if let Some(owner) = use_case.calls.last().and_then(|c| infra_owners.get(&c.target)) {
                        use_case.owner = Some(owner.clone());
                    }
                }
            }
            _ => {}
        }
    }
    Ok(out)
}
