//! `--emit-ts=<file>` / `--emit-openapi=<file>`: describe every HTTP
//! adapter of a `.tr` file for its clients — a typed TypeScript client, or
//! an OpenAPI 3.1 document. Both follow the generated server exactly: the
//! same input/output types, `envelope`, `json_case`, path / query / body
//! split and auth.

use heck::{ToLowerCamelCase, ToUpperCamelCase};
use serde_json::{Map, Value, json};

use crate::{
    generator::{
        CodeGen, CodeGenContext,
        rust_code::types::RustType,
        schema::{collect_named_types, json_schema, ts_declaration, ts_type, wire_name},
    },
    parser::{AdapterType, Ast, HttpMethod, path_params_of},
};

/// One HTTP route, resolved for clients.
struct ClientRoute {
    adapter: String,
    method: HttpMethod,
    path: String,
    use_case: String,
    input: RustType,
    /// What the response body is (entity, list or the use case output).
    output: RustType,
    raw_input: bool,
    auth: bool,
}

fn method_name(method: &HttpMethod) -> &'static str {
    match method {
        HttpMethod::Get => "GET",
        HttpMethod::Post => "POST",
        HttpMethod::Put => "PUT",
        HttpMethod::Patch => "PATCH",
        HttpMethod::Delete => "DELETE",
    }
}

impl CodeGen {
    fn client_routes(&self, asts: &[Ast]) -> Result<(Vec<ClientRoute>, CodeGenContext), String> {
        let asts = &crate::generator::desugar::desugar(asts.to_vec())?;
        let context = self.build_lookup_context(asts)?;
        let mut routes = Vec::new();
        for ast in asts {
            let Ast::Adapter(adapter) = ast else { continue };
            let AdapterType::Http(http) = &adapter.adapter_type else { continue };
            for route in &http.routes {
                let io = context
                    .find_use_case_io(&route.use_case)
                    .ok_or_else(|| format!("route '{}': unknown use_case '{}'", route.path, route.use_case))?;
                let output = match (&io.output_wrapper_field, http.envelope) {
                    (Some(field), false) => io
                        .output_type
                        .fields
                        .iter()
                        .find(|f| &f.name == field)
                        .map(|f| f.field_type.clone())
                        .unwrap_or_else(|| io.output_type.clone()),
                    _ => io.output_type.clone(),
                };
                routes.push(ClientRoute {
                    adapter: adapter.name.clone(),
                    method: route.method.clone(),
                    path: route.path.clone(),
                    use_case: route.use_case.clone(),
                    input: io.input_type.clone(),
                    output,
                    raw_input: io.raw_input,
                    auth: route.auth.is_some(),
                });
            }
        }
        Ok((routes, context))
    }

    /// A TypeScript module: one declaration per type the routes use and one
    /// client class per HTTP adapter.
    pub fn emit_typescript(&self, asts: &[Ast]) -> Result<String, String> {
        let (routes, context) = self.client_routes(asts)?;
        let camel = context.json_camel();

        let mut named: Vec<RustType> = Vec::new();
        for route in &routes {
            if !route.raw_input {
                collect_named_types(&route.input, &mut named);
            }
            collect_named_types(&route.output, &mut named);
        }

        let mut out = String::from(
            "// Generated by trust — do not edit, regenerate with `trust <file.tr> --emit-ts=<this file>`.\n\n",
        );
        for t in &named {
            out.push_str(&ts_declaration(t, camel));
            out.push('\n');
        }
        out.push_str(TS_RUNTIME);

        let mut adapters: Vec<&str> = routes.iter().map(|r| r.adapter.as_str()).collect();
        adapters.dedup();
        for adapter in adapters {
            out.push_str(&format!("\nexport class {}Client extends TrustClient {{\n", adapter.to_upper_camel_case()));
            let mut used: Vec<String> = Vec::new();
            for route in routes.iter().filter(|r| r.adapter == adapter) {
                let base = route.use_case.trim_end_matches("UseCase").to_lower_camel_case();
                let mut name = base.clone();
                if used.contains(&name) {
                    name = format!("{}{}", base, method_name(&route.method).to_lower_camel_case().to_upper_camel_case());
                }
                used.push(name.clone());

                let params = path_params_of(&route.path);
                let mut url = String::new();
                for segment in route.path.split('/').filter(|s| !s.is_empty()) {
                    url.push('/');
                    match segment.strip_prefix(':') {
                        Some(param) => url.push_str(&format!(
                            "${{encodeURIComponent(String(input.{}))}}",
                            wire_name(param, camel)
                        )),
                        None => url.push_str(segment),
                    }
                }
                if url.is_empty() {
                    url.push('/');
                }
                let (arg, call) = if route.raw_input {
                    ("body: string".to_string(), "this.send(method, path, undefined, body)".to_string())
                } else {
                    let path_keys: Vec<String> = params.iter().map(|p| format!("{:?}", wire_name(p, camel))).collect();
                    // GET reads its fields from the query string; every other
                    // method from a JSON body (path fields are ignored there).
                    let call = if route.method == HttpMethod::Get {
                        format!("this.send(method, path, omit(input, [{}]))", path_keys.join(", "))
                    } else {
                        "this.send(method, path, undefined, JSON.stringify(input))".to_string()
                    };
                    (format!("input: {}", ts_type(&route.input)), call)
                };
                out.push_str(&format!(
                    "  /** {} {}{} */\n  {}({}): Promise<{}> {{\n    const method = {:?};\n    const path = `{}`;\n    return {};\n  }}\n\n",
                    method_name(&route.method),
                    route.path,
                    if route.auth { " (authenticated)" } else { "" },
                    name,
                    arg,
                    ts_type(&route.output),
                    method_name(&route.method),
                    url,
                    call
                ));
            }
            out = out.trim_end().to_string();
            out.push_str("\n}\n");
        }
        Ok(out)
    }

    /// An OpenAPI 3.1 document (JSON) for every HTTP adapter.
    pub fn emit_openapi(&self, asts: &[Ast], title: &str) -> Result<String, String> {
        let (routes, context) = self.client_routes(asts)?;
        let camel = context.json_camel();
        let mut paths = Map::new();
        for route in &routes {
            let params = path_params_of(&route.path);
            let openapi_path: String = route
                .path
                .split('/')
                .map(|s| match s.strip_prefix(':') {
                    Some(p) => format!("{{{}}}", p),
                    None => s.to_string(),
                })
                .collect::<Vec<_>>()
                .join("/");
            let mut operation = Map::new();
            operation.insert("operationId".into(), json!(route.use_case));
            operation.insert("tags".into(), json!([route.adapter]));

            let field_schema = |name: &str| {
                route
                    .input
                    .fields
                    .iter()
                    .find(|f| f.name == name)
                    .map(|f| (json_schema(&f.field_type, camel), !f.field_type.is_option()))
            };
            let mut parameters: Vec<Value> = params
                .iter()
                .map(|p| {
                    let (schema, _) = field_schema(p).unwrap_or((json!({ "type": "string" }), true));
                    json!({ "name": p, "in": "path", "required": true, "schema": schema })
                })
                .collect();
            if route.raw_input {
                operation.insert(
                    "requestBody".into(),
                    json!({ "required": true, "content": { "text/plain": { "schema": { "type": "string" } } } }),
                );
            } else if route.method == HttpMethod::Get {
                for field in route.input.fields.iter().filter(|f| !params.contains(&f.name)) {
                    parameters.push(json!({
                        "name": wire_name(&field.name, camel),
                        "in": "query",
                        "required": !field.field_type.is_option(),
                        "schema": json_schema(&field.field_type, camel),
                    }));
                }
            } else if route.input.fields.iter().any(|f| !params.contains(&f.name)) {
                let mut body = route.input.clone();
                body.fields.retain(|f| !params.contains(&f.name));
                operation.insert(
                    "requestBody".into(),
                    json!({ "required": true, "content": { "application/json": { "schema": json_schema(&body, camel) } } }),
                );
            }
            if !parameters.is_empty() {
                operation.insert("parameters".into(), Value::Array(parameters));
            }
            operation.insert(
                "responses".into(),
                json!({
                    "200": { "description": "OK", "content": { "application/json": { "schema": json_schema(&route.output, camel) } } },
                    "404": { "description": "Not found" },
                    "422": { "description": "Invalid input" },
                }),
            );
            if route.auth {
                operation.insert("security".into(), json!([{ "bearer": [] }]));
            }
            let entry = paths.entry(openapi_path).or_insert_with(|| json!({}));
            entry[method_name(&route.method).to_lowercase()] = Value::Object(operation);
        }
        let document = json!({
            "openapi": "3.1.0",
            "info": { "title": title, "version": "1.0.0" },
            "paths": paths,
            "components": { "securitySchemes": { "bearer": { "type": "http", "scheme": "bearer" } } },
        });
        serde_json::to_string_pretty(&document).map_err(|e| e.to_string())
    }
}

/// Shared by every generated client class.
const TS_RUNTIME: &str = r#"export class ApiError extends Error {
  constructor(public status: number, public body: string) {
    super(`HTTP ${status}: ${body}`);
  }
}

export interface ClientOptions {
  /** e.g. "https://api.example.com" (no trailing slash needed). */
  baseUrl: string;
  /** Sent as `Authorization: Bearer <token>` when it returns a value. */
  token?: () => string | null | undefined;
  fetch?: typeof fetch;
}

function omit(input: object, keys: string[]): Record<string, unknown> {
  return Object.fromEntries(Object.entries(input).filter(([key]) => !keys.includes(key)));
}

export class TrustClient {
  constructor(protected options: ClientOptions) {}

  protected async send<T>(method: string, path: string, query?: Record<string, unknown>, body?: string): Promise<T> {
    const url = new URL(this.options.baseUrl.replace(/\/$/, "") + path);
    for (const [key, value] of Object.entries(query ?? {})) {
      if (value !== undefined && value !== null) url.searchParams.set(key, String(value));
    }
    const headers: Record<string, string> = {};
    if (body !== undefined) headers["Content-Type"] = "application/json";
    const token = this.options.token?.();
    if (token) headers["Authorization"] = `Bearer ${token}`;
    const response = await (this.options.fetch ?? fetch)(url, { method, headers, body });
    const text = await response.text();
    if (!response.ok) throw new ApiError(response.status, text);
    return (text ? JSON.parse(text) : undefined) as T;
  }
}
"#;
