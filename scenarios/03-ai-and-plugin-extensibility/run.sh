#!/usr/bin/env bash
# Scenario 3: an `ai {}` use case (mocked LLM) + a dynamically loaded
# `--plugin` extending the language with a new `note {}` construct. See
# scenario.md for what this proves.
set -euo pipefail

SCENARIO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib.sh
source "$SCENARIO_DIR/../lib.sh"

scenario_build_cli
so_path="$(scenario_build_note_plugin)"

log_step "Starting a mock Anthropic server"
read -r base_url mock_pid <<< "$(scenario_start_mock_anthropic 'Ok(SummarizeResponse { summary: input.text })')"
log_pass "mock server listening at $base_url"

workdir="$(scenario_workdir)"
trap 'scenario_stop_mock_anthropic "$mock_pid"; scenario_cleanup "$workdir"' EXIT

scenario_run "$workdir" "$SCENARIO_DIR/app.tr" \
    "--plugin=$so_path" \
    "--ai-base-url=$base_url" \
    "--ai-api-key=test-key"

log_step "Checking generated files exist"
for f in \
    main/src/domains/doc.rs \
    main/src/infrastructures/storage/psql/doc.rs \
    main/src/applications/summarize_use_case.rs \
    main/src/adapters/http/http_adapter/summarize_use_case_post.rs \
    main/src/plugins/note.rs \
    main/src/plugins.rs
do
    [ -f "$workdir/out/$f" ] || log_fail "expected generated file missing: $f"
done
log_pass "all expected files were generated (ai use case + plugin output)"

log_step "Checking the AI-authored body was spliced in verbatim"
grep -qF 'Ok(SummarizeResponse { summary: input.text })' "$workdir/out/main/src/applications/summarize_use_case.rs" \
    || log_fail "summarize_use_case.rs doesn't contain the mocked AI response body"
log_pass "ai {} use case body matches the mocked LLM response"

log_step "Checking the plugin's own template rendered correctly"
grep -qF 'generated by the ai-and-plugin-extensibility scenario' "$workdir/out/main/src/plugins/note.rs" \
    || log_fail "note.rs doesn't contain the note {} block's message"
grep -qF "mod note;" "$workdir/out/main/src/plugins.rs" || log_fail "src/plugins.rs doesn't wire in the note plugin module"
log_pass "note {} plugin construct rendered and got wired into the generated project"

scenario_build_generated "$workdir"
log_pass "generated AI-use-case + plugin project compiles"
